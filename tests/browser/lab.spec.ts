test('arrow keys shift once per press, buttons work, and fixed RPM locks gears', async ({ page }) => {
  await page.goto('/')
  const gear = page.getByLabel('Current gear', { exact: true })
  await expect(gear).toHaveText('N')
  await page.getByRole('button', { name: 'Start engine' }).click()
  await page.keyboard.down('ArrowUp')
  await expect(gear).toHaveText('1')
  await page.waitForTimeout(220)
  await page.keyboard.down('ArrowUp') // Repeated keydown must not advance again.
  await expect(gear).toHaveText('1')
  await page.keyboard.up('ArrowUp')
  await page.keyboard.down('Space'); await page.waitForTimeout(650); await page.keyboard.up('Space')
  const before = await rpm(page)
  await page.keyboard.press('ArrowUp')
  await expect(gear).toHaveText('2')
  await page.waitForTimeout(200)
  expect(await rpm(page)).toBeLessThan(before * 0.8)
  await page.keyboard.press('ArrowDown')
  await expect(gear).toHaveText('1')
  await page.waitForTimeout(220)
  await page.getByRole('button', { name: 'Shift down', exact: true }).click()
  await expect(gear).toHaveText('N')
  await page.waitForTimeout(220)
  await page.getByRole('button', { name: 'Shift up', exact: true }).click()
  await expect(gear).toHaveText('1')
  await page.getByLabel('Fixed RPM', { exact: true }).check()
  await page.getByRole('heading', { name: 'Custom', exact: true }).click()
  await page.keyboard.press('ArrowUp'); await page.keyboard.press('ArrowDown')
  await expect(gear).toHaveText('1')
  await expect(page.getByRole('button', { name: 'Shift up', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Shift down', exact: true })).toBeDisabled()
  await page.getByLabel('Fixed RPM value').focus()
  await page.keyboard.press('ArrowUp')
  await expect(gear).toHaveText('1')
  await page.getByRole('button', { name: 'Stop engine' }).click()
  await expect(gear).toHaveText('N')
})
