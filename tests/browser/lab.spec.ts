import { test, expect, type Page } from '@playwright/test'

async function installProbe(page: Page) {
  await page.addInitScript(() => {
    const create = AudioContext.prototype.createAnalyser
    AudioContext.prototype.createAnalyser = function () {
      const node = create.call(this)
      ;(window as unknown as { audioProbe: AnalyserNode }).audioProbe = node
      return node
    }
  })
}
async function audioRms(page: Page) {
  return page.evaluate(() => {
    const probe = (window as unknown as { audioProbe: AnalyserNode }).audioProbe
    const buffer = new Float32Array(probe.fftSize); probe.getFloatTimeDomainData(buffer)
    return Math.sqrt(buffer.reduce((sum, x) => sum + x * x, 0) / buffer.length)
  })
}
const rpm = async (page: Page) => Number((await page.locator('.dial-readout strong').innerText()).replaceAll(',', ''))

